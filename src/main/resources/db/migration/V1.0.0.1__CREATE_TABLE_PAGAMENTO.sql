CREATE TABLE PAGAMENTO (
    ID_PAGAMENTO VARCHAR(36) NOT NULL PRIMARY KEY,
    TXT_CPF_CNPJ_PAGADOR VARCHAR(14) NOT NULL,
    TXT_CPF_CNPJ_RECEBEDOR VARCHAR(14) NOT NULL,
    TPO_PAGAMENTO VARCHAR(20) NOT NULL,
    NUM_VALOR_TOTAL DECIMAL(18, 2) NOT NULL,
    DAT_CRIACAO_REGISTRO TIMESTAMP NOT NULL,
    DAT_ALTERACAO_REGISTRO TIMESTAMP NOT NULL
);